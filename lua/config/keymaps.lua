local map = vim.keymap.set

map("n", "<Esc>", "<cmd>nohlsearch<cr>", { desc = "Clear search highlighting" })
map({ "i", "n", "x", "s" }, "<C-s>", "<cmd>w<cr><Esc>", { desc = "Save file" })
map("n", "<leader>qq", "<cmd>qa<cr>", { desc = "Quit" })
map("n", "<leader>l", "<cmd>Lazy<cr>", { desc = "Plugins" })
map("n", "<leader>cl", "<cmd>checkhealth vim.lsp<cr>", { desc = "LSP info" })
map("n", "<leader>cd", vim.diagnostic.open_float, { desc = "Line diagnostics" })

for _, direction in ipairs({ "h", "j", "k", "l" }) do
  map("n", "<C-" .. direction .. ">", "<C-w>" .. direction, { desc = "Move to window " .. direction })
end
map("n", "<S-h>", "<cmd>bprevious<cr>", { desc = "Previous buffer" })
map("n", "<S-l>", "<cmd>bnext<cr>", { desc = "Next buffer" })
map("t", "<Esc><Esc>", "<C-\\><C-n>", { desc = "Terminal normal mode" })

-- Navigation and terminals follow the global cwd, without guessing project roots.
local function cwd()
  return { cwd = vim.fn.getcwd(-1, -1) }
end
map("n", "<leader><space>", function()
  Snacks.picker.files(cwd())
end, { desc = "Find files" })
map("n", "<leader>ff", function()
  Snacks.picker.files(cwd())
end, { desc = "Find files" })
map("n", "<leader>/", function()
  Snacks.picker.grep(cwd())
end, { desc = "Live grep" })
map("n", "<leader>sg", function()
  Snacks.picker.grep(cwd())
end, { desc = "Live grep" })
map("n", "<leader>e", function()
  Snacks.explorer(cwd())
end, { desc = "File explorer" })
map("n", "<leader>fe", function()
  Snacks.explorer(cwd())
end, { desc = "File explorer" })
map("n", "<leader>,", function()
  Snacks.picker.buffers()
end, { desc = "Buffers" })
map("n", "<leader>bd", function()
  Snacks.bufdelete()
end, { desc = "Delete buffer" })
map("n", "<leader>sh", function()
  Snacks.picker.help()
end, { desc = "Help" })
map("n", "<leader>sk", function()
  Snacks.picker.keymaps()
end, { desc = "Keymaps" })
map("n", "<leader>sd", function()
  Snacks.picker.diagnostics()
end, { desc = "Diagnostics" })
map("n", "<leader>gg", function()
  Snacks.lazygit(cwd())
end, { desc = "Lazygit" })
map("n", "<leader>gl", function()
  Snacks.picker.git_log(cwd())
end, { desc = "Git log" })
map("n", "<leader>gd", function()
  Snacks.picker.git_diff(cwd())
end, { desc = "Git diff" })
map({ "n", "t" }, "<C-/>", function()
  Snacks.terminal(nil, cwd())
end, { desc = "Terminal" })
map({ "n", "t" }, "<C-_>", function()
  Snacks.terminal(nil, cwd())
end, { desc = "Terminal" })

map({ "n", "x" }, "<leader>cf", function()
  vim.lsp.buf.format({ async = true })
end, { desc = "Format" })
map("n", "<leader>uf", function()
  vim.g.disable_autoformat = not vim.g.disable_autoformat
  vim.notify("Format on save: " .. (vim.g.disable_autoformat and "off" or "on"))
end, { desc = "Toggle format on save" })
